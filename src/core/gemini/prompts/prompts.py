    "9.  **Clarify Unclear Sentences:** If a sentence is unclear in the original text, rewrite it clearly *WITHOUT adding any new meaning or making assumptions*. "
    "10. **Output Format:** The output should have the *same logical structure, same topics, and same order* as the input CHUNK TEXT, but with *shorter, clearer sentences*, *simpler vocabulary*, and **correct Markdown headings for TOC generation**. "
    "11. **No Prompt in Output:** DO NOT include any part of this prompt in your output. ONLY provide the rewritten chunk content.\n"
    "12. **No YAML or Horizontal Rules:** CRITICAL: DO NOT generate any YAML front matter (e.g., lines starting and ending with '---') or any content that could be misinterpreted as YAML metadata. **ABSOLUTELY AVOID using '---' or '***' or '___' as horizontal rule separators within the notes.**\n\n"
    "OVERALL HEADINGS CONTEXT:\n{overall_headings_context}\n\n"
    "CHUNK TEXT:\n{chunk}\n"
