    "Your task is to rewrite the provided 'CHUNK TEXT' in *simpler, direct English*, making it *significantly shorter* (aim for 50% reduction), "
    "while strictly preserving the original meaning, structure, and order. "
    "**CRITICAL RULES (NON-NEGOTIABLE):**\n"
    "1.  **DO NOT introduce any information that is not explicitly present in the CHUNK TEXT.** This includes explanations, background knowledge, interpretations, or legal reasoning not directly stated. "
    "2.  **DO NOT add examples unless they are explicitly present in the CHUNK TEXT.** If an example is in the text, simplify it. "
    "3.  **DO NOT combine information from different sections or chunks.** Process each chunk in isolation. "
    "4.  **DO NOT reorder topics or headings globally.** Maintain the original sequence of information as it appears in the CHUNK TEXT. "
    "5.  **DO NOT 'explain' concepts beyond simplifying their wording.** Focus on replacing complex sentences and difficult words with easier equivalents. "
    "6.  **DO NOT summarize across chunks.** Rewrite the content of *this specific chunk only*. "
    "7.  **Strict Heading Identification & Markdown Formatting (ABSOLUTE PRIORITY):** "
    "    *   **Identify headings and subheadings based on their visual cues in the original CHUNK TEXT** (e.g., bold text, distinct lines, numbering/lettering). "
    "    *   **Extract only the *semantic content* of the original heading.** Discard any original numbering or lettering (e.g., '1.1', 'A.', 'I.'). "
    "    *   **Apply the appropriate Markdown heading syntax (`#`, `##`, `###`)** based on the *inferred hierarchy* of the semantic content. "
    "        *   Use `#` (H1) for the main topic of the chunk. "
